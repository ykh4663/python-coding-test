SELECT 
YEAR(A.DIFFERENTIATION_DATE) AS YEAR,
(B.MX_COL - A.SIZE_OF_COLONY) AS YEAR_DEV,
A.ID
FROM ECOLI_DATA AS A
JOIN MX_EC B
ON YEAR(A.DIFFERENTIATION_DATE) = B.MX_YEAR
ORDER BY YEAR, YEAR_DEV;