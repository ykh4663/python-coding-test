WITH MX_EC AS (
SELECT YEAR(DIFFERENTIATION_DATE) AS MX_YEAR,
    MAX(SIZE_OF_COLONY) AS MX_COL
FROM ECOLI_DATA 
GROUP BY YEAR(DIFFERENTIATION_DATE))

